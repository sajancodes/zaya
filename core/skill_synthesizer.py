"""Dynamic Skill & Tool Synthesizer for Zaya.
Created and developed by Sajan Rai for Zaya.

Enables Zaya to dynamically synthesize, validate, hot-load, and test new tools
at runtime when encountering capabilities not covered by built-in actions.
Synthesized tools are immediately registered in ActionRegistry and indexed
in KnowledgeStore for instant retrieval and execution.
"""
from __future__ import annotations

import ast
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from core.action_loader import get_action_registry
from core.runtime_paths import get_resource_dir
from core.tool_result import ToolResult
from memory.knowledge_store import KnowledgeStore

_VALID_NAME_RE = re.compile(r"^[a-zA-Z_][a-zA-Z0-9_]{0,63}$")


class SkillSynthesizer:
    def __init__(self, actions_dir: Optional[Path] = None):
        if actions_dir is None:
            actions_dir = get_resource_dir() / "actions"
            if not actions_dir.is_dir():
                actions_dir = Path(__file__).resolve().parent.parent / "actions"
        self.actions_dir = actions_dir
        self.actions_dir.mkdir(parents=True, exist_ok=True)

    def validate_code_safety(self, code: str) -> Tuple[bool, str]:
        """Performs static AST validation and security checks."""
        try:
            tree = ast.parse(code)
        except SyntaxError as e:
            return False, f"Syntax error in synthesized code: {e}"

        # Security check: disallow destructive operations or token theft
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                func_name = ""
                if isinstance(node.func, ast.Name):
                    func_name = node.func.id
                elif isinstance(node.func, ast.Attribute):
                    func_name = node.func.attr

                # Block direct shell formatting injection or raw system wipes
                if func_name in ("rmtree", "system", "popen", "spawn"):
                    # Check if imported from dangerous modules
                    for arg in node.args:
                        if isinstance(arg, ast.Constant) and str(arg.value).strip() in ("/", "C:\\", "C:/"):
                            return False, "Dangerous filesystem operation detected on system root."

        return True, "Code passed static safety analysis."

    def scaffold_tool_code(
        self,
        name: str,
        description: str,
        parameters: Dict[str, Any],
        raw_code: str,
    ) -> str:
        """Wraps raw function code into a complete, conforming Zaya action module."""
        clean_name = name.strip()
        if not clean_name.startswith("custom_"):
            clean_name = f"custom_{clean_name}"

        # Check if code already defines TOOL
        if "TOOL =" in raw_code or "TOOLS =" in raw_code:
            return raw_code

        # Check if code defines handler
        has_handler = f"def {name}(" in raw_code or f"def {clean_name}(" in raw_code or "def run(" in raw_code

        if not has_handler:
            # Wrap as simple execution body
            body_lines = ["    " + line for line in raw_code.strip().splitlines()]
            raw_code = f"def {clean_name}(parameters: dict, **_kwargs) -> ToolResult:\n" + "\n".join(body_lines)

        params_json = json.dumps(parameters, indent=4)

        scaffold = f'''"""Synthesized Action: {clean_name}
Auto-generated by Zaya Dynamic Skill Synthesizer.
"""
from __future__ import annotations

import json
from core.execution_policy import require_owner
from core.tool_result import ToolResult

{raw_code.strip()}

TOOL = {{
    "name": "{clean_name}",
    "description": {json.dumps(description)},
    "parameters": {params_json},
    "handler": {clean_name if f"def {clean_name}(" in raw_code else (name if f"def {name}(" in raw_code else "run")},
}}
'''
        return scaffold

    def synthesize(
        self,
        name: str,
        description: str,
        parameters: Dict[str, Any],
        python_code: str,
        test_parameters: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Synthesizes, writes, hot-loads, and verifies a custom skill tool."""
        # Parameter schema validation
        if not isinstance(parameters, dict):
            return {
                "status": "failed",
                "error": "Invalid tool schema: parameters must be a dictionary.",
            }
        p_type = str(parameters.get("type", "")).upper()
        if p_type != "OBJECT":
            return {
                "status": "failed",
                "error": "Invalid tool schema: parameters must specify 'type': 'OBJECT'.",
            }
        if not isinstance(parameters.get("properties"), dict):
            return {
                "status": "failed",
                "error": "Invalid tool schema: parameters must include a 'properties' dictionary.",
            }

        clean_name = name.strip().lower()
        if not _VALID_NAME_RE.match(clean_name):
            return {
                "status": "failed",
                "error": f"Invalid tool name '{name}'. Must match ^[a-zA-Z_][a-zA-Z0-9_]{{0,63}}$",
            }

        if not clean_name.startswith("custom_"):
            target_name = f"custom_{clean_name}"
        else:
            target_name = clean_name

        # Immutable built-in protection and collision detection
        registry = get_action_registry(self.actions_dir)
        if clean_name in registry._builtin_names or target_name in registry._builtin_names:
            return {
                "status": "failed",
                "error": f"Collision: Cannot overwrite built-in core action '{clean_name}'. Core tools are immutable.",
            }

        full_code = self.scaffold_tool_code(clean_name, description, parameters, python_code)

        valid, reason = self.validate_code_safety(full_code)
        if not valid:
            return {"status": "failed", "error": f"Safety verification failed: {reason}"}

        target_file = self.actions_dir / f"{target_name}.py"
        try:
            target_file.write_text(full_code, encoding="utf-8")
        except Exception as e:
            return {"status": "failed", "error": f"Failed to write file {target_file}: {e}"}

        # Hot-load into ActionRegistry
        try:
            loaded_records = registry.load_action_file(target_file)
        except Exception as e:
            # Clean up on failed load
            try:
                target_file.unlink()
            except Exception:
                pass
            import sys
            sys.modules.pop(f"actions.{target_name}", None)
            return {"status": "failed", "error": f"Hot-loading failed: {e}"}

        if not loaded_records or not any(r.valid for r in loaded_records):
            err = loaded_records[0].error if loaded_records else "No valid TOOL found in module"
            try:
                target_file.unlink()
            except Exception:
                pass
            import sys
            sys.modules.pop(f"actions.{target_name}", None)
            return {"status": "failed", "error": f"Action validation failed: {err}"}
            return {"status": "failed", "error": f"Action validation failed: {err}"}

        loaded_name = loaded_records[0].name

        # Execute test run if parameters supplied
        test_result = None
        if test_parameters is not None:
            try:
                raw_out = registry.run(loaded_name, test_parameters)
                test_result = str(raw_out)
            except Exception as e:
                test_result = f"Test execution error: {e}"

        # Index in KnowledgeStore
        try:
            kstore = KnowledgeStore.get_store()
            kstore.put_fact(
                category="synthesized_skill",
                key=loaded_name,
                value=json.dumps({
                    "name": loaded_name,
                    "description": description,
                    "parameters": parameters,
                    "file": target_file.name,
                }),
            )
        except Exception:
            pass

        return {
            "status": "success",
            "name": loaded_name,
            "file": str(target_file),
            "test_result": test_result,
            "message": f"Skill '{loaded_name}' successfully synthesized and hot-loaded into active action registry.",
        }

    def list_skills(self) -> List[Dict[str, Any]]:
        """Lists all synthesized custom skills."""
        results = []
        for file in self.actions_dir.glob("custom_*.py"):
            try:
                content = file.read_text(encoding="utf-8")
                name = file.stem
                # Extract description if possible
                m_desc = re.search(r'"description":\s*"(.*?)"', content)
                desc = m_desc.group(1) if m_desc else "Custom synthesized skill"
                results.append({
                    "name": name,
                    "file": str(file),
                    "description": desc,
                })
            except Exception:
                pass
        return results

    def remove_skill(self, name: str) -> Dict[str, Any]:
        """Unregisters and removes a synthesized custom skill."""
        clean_name = name.strip()
        if not clean_name.startswith("custom_"):
            target_name = f"custom_{clean_name}"
        else:
            target_name = clean_name

        registry = get_action_registry(self.actions_dir)
        registry.unregister_action(target_name)

        target_file = self.actions_dir / f"{target_name}.py"
        deleted = False
        if target_file.is_file():
            try:
                target_file.unlink()
                deleted = True
            except Exception as e:
                return {"status": "failed", "error": f"Failed to delete {target_file}: {e}"}

        return {
            "status": "success" if deleted else "not_found",
            "name": target_name,
            "deleted": deleted,
            "message": f"Skill '{target_name}' {'removed' if deleted else 'was not found'}.",
        }


# Global singleton
_synthesizer: Optional[SkillSynthesizer] = None


def get_skill_synthesizer() -> SkillSynthesizer:
    global _synthesizer
    if _synthesizer is None:
        _synthesizer = SkillSynthesizer()
    return _synthesizer
